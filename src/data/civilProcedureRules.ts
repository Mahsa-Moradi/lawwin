import type { DeadlineRule } from "@/types/deadline";
import { DEADLINE_CATEGORY_CIVIL_PROCEDURE } from "@/data/deadlineCategories";
import { buildDurationLabel } from "@/lib/deadline/durationLabel";

const STARTS_FROM = "از روز بعد از ابلاغ / ابلاغ";

function civilRule(
  id: string,
  title: string,
  durations: readonly number[],
  description: string,
): DeadlineRule {
  const d = [...durations];
  return {
    id,
    categoryId: DEADLINE_CATEGORY_CIVIL_PROCEDURE,
    title,
    durations: d,
    durationLabel: buildDurationLabel(d),
    days: d[0] ?? 0,
    description,
    startsFrom: STARTS_FROM,
    needsLegalReview: true,
    calculationMode: "civil_procedure",
  };
}

